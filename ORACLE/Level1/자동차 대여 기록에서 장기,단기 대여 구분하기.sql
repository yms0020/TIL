-- 문제: 자동차 대여 기록에서 장기/단기 대여 구분하기
-- 플랫폼: 프로그래머스
-- 언어: Oracle
-- 난이도: Level 1
-- URL: https://school.programmers.co.kr/learn/courses/30/lessons/151138

내 답: 오답
SELECT HISTORY_ID, CAR_ID, START_DATE, END_DATE,
       CASE
           WHEN END_DATE - START_DATE < 30 THEN '단기 대여'
           WHEN END_DATE - START_DATE >= 30 THEN '장기 대여'
       END AS RENT_TYPE
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY 
WHERE START_DATE >= DATE '2022-09-01'
  AND START_DATE < DATE '2022-10-01'
ORDER BY HISTORY_ID DESC;

정답:
SELECT HISTORY_ID,
       CAR_ID,
       TO_CHAR(START_DATE, 'YYYY-MM-DD') AS START_DATE,
       TO_CHAR(END_DATE, 'YYYY-MM-DD') AS END_DATE,
       CASE
           WHEN END_DATE - START_DATE + 1 >= 30 THEN '장기 대여'
           ELSE '단기 대여'
       END AS RENT_TYPE
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
WHERE START_DATE >= DATE '2022-09-01'
  AND START_DATE < DATE '2022-10-01'
ORDER BY HISTORY_ID DESC;
