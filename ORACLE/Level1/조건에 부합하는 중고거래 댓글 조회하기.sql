내 답: 
SELECT UGB.TITLE,UGB.BOARD_ID,UGR.REPLY_ID,UGR.WRITER_ID,UGR.CONTENTS,UGR.CREATED_DATE
FROM USED_GOODS_BOARD UGB,USED_GOODS_REPLY UGR 
WHERE UGB.BOARD_ID = UGR.BOARD_ID AND 
UGB.CREATED_DATE >= DATE '2022-10-01' AND UGB.CREATED_DATE < DATE '2022-11-01' 
ORDER BY UGR.CREATED_DATE,UGB.TITLE;

정답1:
SELECT UGB.TITLE,UGB.BOARD_ID,UGR.REPLY_ID,UGR.WRITER_ID,UGR.CONTENTS,TO_CHAR(UGR.CREATED_DATE, 'YYYY-MM-DD') AS CREATED_DATE
FROM USED_GOODS_BOARD UGB,USED_GOODS_REPLY UGR 
WHERE UGB.BOARD_ID = UGR.BOARD_ID AND 
UGB.CREATED_DATE >= DATE '2022-10-01' AND UGB.CREATED_DATE < DATE '2022-11-01' 
ORDER BY UGR.CREATED_DATE,UGB.TITLE;

정답2(추천):
SELECT B.TITLE,
       B.BOARD_ID,
       R.REPLY_ID,
       R.WRITER_ID,
       R.CONTENTS,
       TO_CHAR(R.CREATED_DATE, 'YYYY-MM-DD') AS CREATED_DATE
FROM USED_GOODS_BOARD B
INNER JOIN USED_GOODS_REPLY R
    ON B.BOARD_ID = R.BOARD_ID
WHERE B.CREATED_DATE >= DATE '2022-10-01'
  AND B.CREATED_DATE < DATE '2022-11-01'
ORDER BY R.CREATED_DATE ASC, B.TITLE ASC;
